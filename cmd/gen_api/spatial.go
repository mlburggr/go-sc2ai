package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"text/template"
)

// imageDataFieldInfo describes an *ImageData struct field and its typed equivalent.
type imageDataFieldInfo struct {
	Name    string // Go field name (e.g., "HeightMap")
	Type    string // Typed wrapper (e.g., "ImageDataBytes")
	Method  string // Conversion method on *ImageData (e.g., "Bytes")
	Comment string // Original trailing comment from proto
}

// imageDataStructInfo describes a struct containing typed *ImageData fields.
type imageDataStructInfo struct {
	Name   string
	Fields []imageDataFieldInfo
}

var spatialTypedTmpl = template.Must(template.New("spatial_typed").Parse(`// Code generated by gen_api. DO NOT EDIT.

package api
{{range .Structs}}
// Typed{{.Name}} provides typed access to {{.Name}} ImageData fields.
// Each field is converted from *ImageData to its typed wrapper
// based on the bits-per-pixel documented in the proto definition.
type Typed{{.Name}} struct {
{{- range .Fields}}
	{{.Name}} {{.Type}} // {{.Comment}}
{{- end}}
}

// Typed converts all ImageData fields to their typed wrappers,
// validating BitsPerPixel for each non-nil field.
func (x *{{.Name}}) Typed() Typed{{.Name}} {
	return Typed{{.Name}}{
{{- range .Fields}}
		{{.Name}}: x.{{.Name}}.{{.Method}}(),
{{- end}}
	}
}
{{end}}
// TypedObservationFeatureLayer wraps typed screen and minimap feature layers.
type TypedObservationFeatureLayer struct {
	Renders        TypedFeatureLayers
	MinimapRenders TypedFeatureLayersMinimap
}

// Typed converts both screen and minimap renders to their typed wrappers.
func (x *ObservationFeatureLayer) Typed() TypedObservationFeatureLayer {
	return TypedObservationFeatureLayer{
		Renders:        x.Renders.Typed(),
		MinimapRenders: x.MinimapRenders.Typed(),
	}
}

// FeatureLayerTyped returns typed feature layer data, or nil if not enabled.
func (x *Observation) FeatureLayerTyped() *TypedObservationFeatureLayer {
	if x == nil || x.FeatureLayerData == nil {
		return nil
	}
	t := x.FeatureLayerData.Typed()
	return &t
}
`))

// generateTypedImageData parses spatial.pb.go for *ImageData fields with
// BPP comments and generates typed wrapper structs and conversion methods.
func generateTypedImageData() {
	content, err := os.ReadFile(filepath.Join("api", "spatial.pb.go"))
	check(err)

	structs := parseImageDataStructs(string(content))
	if len(structs) == 0 {
		fmt.Println("Warning: no ImageData structs found in spatial.pb.go")
		return
	}

	var buf strings.Builder
	check(spatialTypedTmpl.Execute(&buf, map[string]any{
		"Structs": structs,
	}))

	outPath := filepath.Join("api", "spatial_typed.go")
	check(os.WriteFile(outPath, []byte(buf.String()), 0644))
	fmt.Printf("Generated %s\n", outPath)
}

// parseImageDataStructs finds struct types in the given Go source that contain
// *ImageData fields with BPP-indicating comments (uint8., 1-bit., int32.).
func parseImageDataStructs(text string) []imageDataStructInfo {
	lines := strings.Split(text, "\n")
	var result []imageDataStructInfo
	var current *imageDataStructInfo

	structRe := regexp.MustCompile(`^type (\w+) struct \{$`)
	fieldRe := regexp.MustCompile(`^\t(\w+)\s+\*ImageData\b.+//\s*(.+)`)

	for _, line := range lines {
		if m := structRe.FindStringSubmatch(line); m != nil {
			s := imageDataStructInfo{Name: m[1]}
			current = &s
			continue
		}
		if current != nil {
			if strings.TrimSpace(line) == "}" {
				if len(current.Fields) > 0 {
					result = append(result, *current)
				}
				current = nil
				continue
			}
			if m := fieldRe.FindStringSubmatch(line); m != nil {
				fieldName, comment := m[1], m[2]
				goType, method := imageDataTypeFromComment(comment)
				if goType != "" {
					current.Fields = append(current.Fields, imageDataFieldInfo{
						Name:    fieldName,
						Type:    goType,
						Method:  method,
						Comment: comment,
					})
				} else {
					fmt.Printf("Warning: unrecognized ImageData type in %s.%s comment: %s\n",
						current.Name, fieldName, comment)
				}
			}
		}
	}
	return result
}

// imageDataTypeFromComment maps a proto field comment prefix to its typed ImageData wrapper.
func imageDataTypeFromComment(comment string) (goType, method string) {
	switch {
	case strings.HasPrefix(comment, "1-bit."):
		return "ImageDataBits", "Bits"
	case strings.HasPrefix(comment, "uint8."):
		return "ImageDataBytes", "Bytes"
	case strings.HasPrefix(comment, "int32."):
		return "ImageDataInt32", "Ints"
	}
	return "", ""
}
